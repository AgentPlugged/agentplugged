import { CHAT_RETENTION_MS } from "@agentplugged/protocol";
import { CREATOR_TEXT_PATTERNS } from "./creator-text.js";

/**
 * The Claude Code hook that proves the chat's quotes: a `UserPromptSubmit`
 * hook of type `command`, never `mcp_tool` (an agent could call an MCP tool itself). Claude Code
 * runs it for each message the creator types or dictates; it records the message (normalised
 * text, digest, time, session, project) in a store of the machine, outside the repository and the journal,
 * kept 24 hours. It records only what the creator typed: the editor's context
 * blocks are removed, and what the tool injects (a sub-agent's report, a notification, another
 * session's message) is never recorded. It never blocks a message: any failure is ignored. It is a generated file without
 * dependency, under `.claude/` (agents may not write there), and agents may not run it.
 */

/** Marker of generated JavaScript files. */
export const GENERATED_HEADER_SLASH =
  "// Generated by agentplugged. Do not edit: changes are overwritten.";

/** Where `sync` writes the script, relative to the project. */
export const PROMPT_HOOK_PATH = ".claude/hooks/agentplugged-prompt.mjs";

/** The name agents may never run (`sync` denies `node …agentplugged-prompt…`). */
export const PROMPT_HOOK_NAME = "agentplugged-prompt";

/** The command Claude Code runs, from the project's folder whatever the session's. */
export const PROMPT_HOOK_COMMAND = `node "$CLAUDE_PROJECT_DIR/${PROMPT_HOOK_PATH}"`;

/** How long Claude Code waits for the hook, in seconds. */
export const PROMPT_HOOK_TIMEOUT = 10;

/** The store's folder under the home folder (`~/.agentplugged/chat`). */
export const CHAT_STORE_DIR = ".agentplugged/chat";

/** What the hook tells the agent: the session id to pass to `chat.answer`. */
export const SESSION_CONTEXT_PREFIX = "agentplugged chat session: ";

/**
 * What the Cursor and the Codex hooks share to read their standard input. On Windows
 * the payload may come through Windows PowerShell 5.1: it comes out of \x60Get-Content\x60 in the
 * system's ANSI code page (UTF-8 bytes read as Windows-1252: an accented e arrives as two
 * characters) and is piped with byte order marks in front; a hook can also receive bytes that are
 * not UTF-8 at all (Windows-1252 or UTF-16). \x60readInput\x60 undoes all of it, so that a message is
 * recorded as the creator typed it. A text that was not garbled does not come back as valid UTF-8
 * from this reading: it is left as it is.
 */
export function inputRepairHelpers(): string {
  return `const CP1252 = (() => {
  const byChar = new Map();
  const decoder = new TextDecoder("windows-1252");
  for (let byte = 0; byte < 256; byte++) byChar.set(decoder.decode(Uint8Array.of(byte)), byte);
  return byChar;
})();

function mend(text) {
  let start = 0;
  while (text.charCodeAt(start) === 0xfeff) start++;
  const plain = text.slice(start);
  // A UTF-8 lead byte read as Windows-1252 is a character from 0xC2 to 0xF4.
  if (![...plain].some((char) => char.charCodeAt(0) >= 0xc2 && char.charCodeAt(0) <= 0xf4)) return plain;
  const bytes = [];
  for (const char of plain) {
    const byte = CP1252.get(char);
    if (byte === undefined) return plain;
    bytes.push(byte);
  }
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(Uint8Array.from(bytes));
  } catch {
    return plain;
  }
}

// The standard input as text: UTF-16 when it opens with its mark, UTF-8 when it is valid, the
// system's Windows-1252 otherwise, then the repair above.
function readInput() {
  const raw = readFileSync(0);
  if (raw.length >= 2 && raw[0] === 0xff && raw[1] === 0xfe) return mend(raw.toString("utf16le"));
  try {
    return mend(new TextDecoder("utf-8", { fatal: true }).decode(raw));
  } catch {
    return mend(new TextDecoder("windows-1252").decode(raw));
  }
}

`;
}

/**
 * The JavaScript both generated hook scripts share (Claude Code's `UserPromptSubmit`, Antigravity's
 * `PreInvocation`): the store's imports, the normalisation of a message, `creatorText`
 * (the rule) and the pruning of the store. One text, so that the two scripts never
 * differ on what a message is nor on how it is kept.
 */
export function chatStoreHelpers(): string {
  return String.raw`import { createHash } from "node:crypto";
import { appendFileSync, mkdirSync, readdirSync, readFileSync, renameSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

const RETENTION_MS = ${CHAT_RETENTION_MS};
const MAX_TEXT = 4000;
const EDGES = /^[\s"'\x60.,;:!…*_~()[\]{}<>«»-]+|[\s"'\x60.,;:!…*_~()[\]{}<>«»-]+$/gu;

function normalize(text) {
  const plain = text
    .normalize("NFKC")
    .replace(/[​-‍⁠﻿︎️]/g, "")
    .replace(/[‘’‚‛′ʼ]/g, "'")
    .replace(/[“”„‟″«»]/g, '"')
    .replace(/[‐-―−]/g, "-")
    .toLowerCase();
  return [...plain]
    .map((char) => {
      const code = char.charCodeAt(0);
      return code < 0x20 || (code >= 0x7f && code < 0xa0) ? " " : char;
    })
    .join("")
    .replace(/\s+/gu, " ")
    .replace(EDGES, "");
}

const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");

const storeDir = () => join(homedir(), ".agentplugged", "chat");

const PATTERNS = ${JSON.stringify(CREATOR_TEXT_PATTERNS)};
const INJECTED = new RegExp(PATTERNS.injected, "i");
const MARKERS = PATTERNS.markers.map((source) => new RegExp(source, "i"));
const LEADING = new RegExp(PATTERNS.leading, "i");
const TRAILING = new RegExp(PATTERNS.trailing, "i");
const ANY_CONTEXT = new RegExp(PATTERNS.anyContext, "i");
const GENERIC_LEADING = new RegExp(PATTERNS.genericLeading, "i");
const WRAPPER_ATTRIBUTES = new RegExp(PATTERNS.wrapperAttributes, "i");
const EDGES_PUNCTUATION = new RegExp(PATTERNS.edges, "gu");

// What the creator typed: the editor's context blocks (<ide_opened_file>…) removed at either end,
// nothing at all (undefined) for what the tool injected itself (a sub-agent's report, a task
// notification, another session's message) or when in doubt. Same rule as creatorText (core).
function creatorText(prompt) {
  if (prompt.length > PATTERNS.maxPrompt) return undefined;
  let text = prompt.trim();
  const leadingTags = new Set();
  for (let blocks = 0; ; blocks++) {
    const open = LEADING.exec(text);
    if (open === null) break;
    const tag = open[1].toLowerCase();
    leadingTags.add(tag);
    const close = text.toLowerCase().indexOf("</" + tag + ">", open[0].length);
    if (close === -1 || blocks >= PATTERNS.maxBlocks) return undefined;
    if (ANY_CONTEXT.test(text.slice(open[0].length, close))) return undefined;
    text = text.slice(close + tag.length + 3).trim();
  }
  for (let blocks = 0; ; blocks++) {
    const close = TRAILING.exec(text);
    if (close === null) break;
    const tag = close[1].toLowerCase();
    const start = text.toLowerCase().lastIndexOf("<" + tag, close.index);
    const open = start === -1 ? null : LEADING.exec(text.slice(start));
    if (open === null || open[1].toLowerCase() !== tag || blocks >= PATTERNS.maxBlocks || leadingTags.has(tag)) return undefined;
    if (ANY_CONTEXT.test(text.slice(start + open[0].length, close.index))) return undefined;
    text = text.slice(0, start).trim();
  }
  const bare = text.replace(EDGES_PUNCTUATION, "");
  for (const probe of [text, bare]) {
    if (
      INJECTED.test(probe) ||
      MARKERS.some((marker) => marker.test(probe)) ||
      GENERIC_LEADING.test(probe) ||
      WRAPPER_ATTRIBUTES.test(probe)
    ) {
      return undefined;
    }
  }
  if (ANY_CONTEXT.test(text)) return undefined;
  return text === "" ? undefined : text;
}

// The prompt as the text rules see it: compatibility form, no invisible character.
const INVISIBLE = new RegExp(PATTERNS.invisible, "g");
const seen = (prompt) => prompt.normalize("NFKC").replace(INVISIBLE, "");

function keep(line, now) {
  try {
    const at = Date.parse(JSON.parse(line).at);
    return !Number.isNaN(at) && now - at <= RETENTION_MS;
  } catch {
    return false;
  }
}

function prune(dir, own, now) {
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".jsonl") && !name.endsWith(".tmp")) continue;
    const file = join(dir, name);
    try {
      if (file === own) {
        const lines = readFileSync(file, "utf8").split("\n").filter((line) => line !== "");
        const kept = lines.filter((line) => keep(line, now));
        if (kept.length !== lines.length) {
          // Written aside, then renamed: a crash never leaves a cut file.
          const next = file + "." + process.pid + ".tmp";
          writeFileSync(next, kept.map((line) => line + "\n").join(""), { mode: 0o600 });
          renameSync(next, file);
        }
      } else if (name.endsWith(".tmp") || now - statSync(file).mtimeMs > RETENTION_MS) {
        unlinkSync(file);
      }
    } catch {}
  }
}

`;
}

/** The script, the same for every product. */
export function renderPromptHookScript(): string {
  return String.raw`${GENERATED_HEADER_SLASH}
// Claude Code UserPromptSubmit hook (agentplugged): records each message the creator types or
// dictates (normalised text, SHA-256 digest, time, session) in ~/.agentplugged/chat/, outside the
// repository and the journal, kept ${CHAT_RETENTION_MS / 3_600_000} hours. chat.answer accepts a quote only when it
// is one of these messages, sent in the session after the checkpoint opened. Never blocks a
// message: any failure is ignored. Agents never run it nor write its store.
${chatStoreHelpers()}// A session started without a terminal (\x60claude -p\x60, the SDK) has no creator typing.
function automatic() {
  return (process.env.CLAUDE_CODE_ENTRYPOINT ?? "").toLowerCase().startsWith("sdk");
}

let session = "";
try {
  const input = JSON.parse(readFileSync(0, "utf8"));
  const id = typeof input.session_id === "string" ? input.session_id.trim() : "";
  if (/^[\x21-\x7e]{1,200}$/.test(id)) session = id;
  const prompt = typeof input.prompt === "string" ? input.prompt : "";
  const typed = creatorText(seen(prompt));
  const text = typed === undefined ? "" : normalize(typed);
  // The project of the session: a message counts for this product only.
  const project = (process.env.CLAUDE_PROJECT_DIR ?? "").trim() || (typeof input.cwd === "string" ? input.cwd : "");
  if (session !== "" && text !== "" && project !== "" && !automatic()) {
    const dir = storeDir();
    mkdirSync(dir, { recursive: true, mode: 0o700 });
    const now = Date.now();
    const file = join(dir, sha256(session).slice(0, 32) + ".jsonl");
    prune(dir, file, now);
    const line = { v: 1, session, project, at: new Date(now).toISOString(), digest: sha256(text), text: text.slice(0, MAX_TEXT) };
    appendFileSync(file, JSON.stringify(line) + "\n", { mode: 0o600 });
  }
} catch {}
if (session !== "") {
  const context = "${SESSION_CONTEXT_PREFIX}" + session + " (pass it as session to chat.answer)";
  process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: "UserPromptSubmit", additionalContext: context } }) + "\n");
}
process.exit(0);
`;
}

/** The hook handler `sync` writes in `.claude/settings.json`. */
export function promptHookHandler(): Record<string, unknown> {
  return { type: "command", command: PROMPT_HOOK_COMMAND, timeout: PROMPT_HOOK_TIMEOUT };
}

/** True for our hook handler: a `command` hook that runs our script. */
export function isPromptHook(value: unknown): boolean {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return false;
  const handler = value as Record<string, unknown>;
  return (
    handler.type === "command" &&
    typeof handler.command === "string" &&
    handler.command.includes(`${PROMPT_HOOK_NAME}.mjs`)
  );
}
