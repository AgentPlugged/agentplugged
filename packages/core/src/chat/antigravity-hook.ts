/** What the agent is told: the engine could not check the tool call, so it is denied. */
export const ANTIGRAVITY_UNCHECKED_REASON =
  "AgentPlugged could not check this tool call (the engine did not answer): it is denied. Try again, and tell the creator if it keeps happening.";

/** The hook handlers `hooks.json` holds, with the script's path relative to the plugin folder. */
export function antigravityHooks(): Record<string, unknown> {
  const script = `hooks/${ANTIGRAVITY_HOOK_NAME}.mjs`;
  const handler = (event: string) => ({
    type: "command",
    command: `node ${script} ${event}`,
    timeout: ANTIGRAVITY_HOOK_TIMEOUT,
  });
  return {
    [ANTIGRAVITY_PLUGIN_NAME]: {
      PreToolUse: [{ matcher: "*", hooks: [handler("pre-tool")] }],
      PostToolUse: [{ matcher: "*", hooks: [handler("post-tool")] }],
      PreInvocation: [handler("pre-invocation")],
    },
  };
}

/**
 * The MCP launch the script runs for the engine's hook: the launch of the MCP server, without its
 * trailing `mcp` argument (`npx -y agentplugged@x`, `cmd /c npx …` on Windows, or the creator's
 * local build).
 */
export function hookLaunch(launch: McpServerLaunch): McpServerLaunch {
  // Up to the last `mcp`: what the creator's own launch puts after it (`--engine-any`) is the
  // server's option, not the hook's.
  const at = launch.args.lastIndexOf("mcp");
  return { command: launch.command, args: at === -1 ? [...launch.args] : launch.args.slice(0, at) };
}

/** The script. It differs from one product to another by the engine's launch only. */
export function renderAntigravityHookScript(launch: McpServerLaunch): string {
  return String.raw`${GENERATED_HEADER_SLASH}
// Antigravity CLI hooks of the agentplugged plugin: the product's permission rules before a tool
// runs (asked of the engine), the reads of external content after one, and the proof of the chat
// (the messages the creator typed, read in the conversation's transcript and recorded in
// ~/.agentplugged/chat/, kept ${CHAT_RETENTION_MS / 3_600_000} hours). Never blocks a model call: any failure of the
// proof is ignored; a tool the engine cannot check is denied. Agents never run it nor write its store.
${chatStoreHelpers()}import { spawnSync } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LAUNCH = ${JSON.stringify(hookLaunch(launch))};
const HARMLESS = new Set(${JSON.stringify(ANTIGRAVITY_HARMLESS_TOOLS)});
const READING = new Set(${JSON.stringify(ANTIGRAVITY_READING_TOOLS)});
const NETWORK = /\b(?:curl|wget|gh|iwr|irm|invoke-webrequest|invoke-restmethod)\b|\bgit\b[^;&|\n]*\b(?:pull|fetch|clone)\b/i;
const OURS = /^(?:agentplugged_)?agentplugged$/;
const UNCHECKED = ${JSON.stringify(ANTIGRAVITY_UNCHECKED_REASON)};
const DECISIONS = new Set(["allow", "deny", "ask", "force_ask"]);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "..");
const folder = (path) => path.replace(/\\/g, "/").replace(/\/+$/, "").toLowerCase();

function answer(value) {
  process.stdout.write(JSON.stringify(value) + "\n");
  process.exit(0);
}

// The engine, started from the project's folder (Antigravity runs the hook from the plugin's).
function engine(event, stdin) {
  const run = spawnSync(LAUNCH.command, [...LAUNCH.args, "hook", "antigravity", event], {
    cwd: ROOT,
    input: stdin,
    encoding: "utf8",
    timeout: 25000,
    windowsHide: true,
    maxBuffer: 1 << 20,
  });
  if (run.error || run.status !== 0) return undefined;
  try {
    const value = JSON.parse(run.stdout);
    return value !== null && typeof value === "object" ? value : undefined;
  } catch {
    return undefined;
  }
}

function toolOf(input) {
  const call = input.toolCall;
  const name = call && typeof call.name === "string" ? call.name : "";
  const args = call && call.args !== null && typeof call.args === "object" ? call.args : {};
  return { name, args };
}

function preTool(stdin) {
  let input = {};
  try {
    input = JSON.parse(stdin);
  } catch {
    answer({ decision: "deny", reason: UNCHECKED });
  }
  const { name, args } = toolOf(input);
  if (name === "") answer({ decision: "deny", reason: UNCHECKED });
  if (HARMLESS.has(name)) answer({ decision: "allow" });
  if (name === "call_mcp_tool" && OURS.test(String(args.ServerName ?? ""))) answer({ decision: "allow" });
  const result = engine("pre-tool", stdin);
  if (result === undefined || !DECISIONS.has(result.decision)) answer({ decision: "deny", reason: UNCHECKED });
  answer(typeof result.reason === "string" ? { decision: result.decision, reason: result.reason } : { decision: result.decision });
}

function postTool(stdin) {
  try {
    const { name, args } = toolOf(JSON.parse(stdin));
    if (!READING.has(name)) answer({});
    if (name === "run_command" && !NETWORK.test(String(args.CommandLine ?? ""))) answer({});
    if (name === "call_mcp_tool" && OURS.test(String(args.ServerName ?? ""))) answer({});
    engine("post-tool", stdin);
  } catch {}
  answer({});
}

// The request of a step of the creator, as Antigravity wraps it: the typed text between the request
// tags, then only the notices the tool itself appends. Anything else: in doubt.
function requestBody(content) {
  const OPEN = "<USER_REQUEST>\n";
  const CLOSE = "\n</USER_REQUEST>";
  if (!content.startsWith(OPEN)) return undefined;
  const end = content.lastIndexOf(CLOSE);
  if (end < OPEN.length) return undefined;
  const rest = content.slice(end + CLOSE.length);
  if (!/^\s*(?:<(ADDITIONAL_METADATA|USER_SETTINGS_CHANGE)>[\s\S]*?<\/\1>\s*)*$/.test(rest)) return undefined;
  return content.slice(OPEN.length, end);
}

// The steps of the transcript already recorded for this session.
function recordedSteps(file) {
  const steps = new Set();
  try {
    for (const line of readFileSync(file, "utf8").split("\n")) {
      if (line === "") continue;
      try {
        const entry = JSON.parse(line);
        if (Number.isInteger(entry.step)) steps.add(entry.step);
      } catch {}
    }
  } catch {}
  return steps;
}

function record(input, conversation) {
  const transcript = typeof input.transcriptPath === "string" ? input.transcriptPath : "";
  const path = transcript.replace(/\\/g, "/");
  const found = /\/\.gemini\/antigravity(?:-cli|-ide)?\/brain\/([0-9a-f-]{8,64})\/\.system_generated\/logs\/transcript_full\.jsonl$/i.exec(path);
  if (found === null || found[1].toLowerCase() !== conversation.toLowerCase()) return;
  if (!folder(path).startsWith(folder(resolve(homedir(), ".gemini")) + "/")) return;
  const hosted = (process.env.ANTIGRAVITY_CONVERSATION_ID ?? "").trim();
  if (hosted !== "" && hosted.toLowerCase() !== conversation.toLowerCase()) return;
  // The session belongs to this product: its workspace is the project's folder or inside it.
  const root = folder(ROOT);
  const workspaces = Array.isArray(input.workspacePaths) ? input.workspacePaths.filter((entry) => typeof entry === "string") : [];
  if (!workspaces.some((entry) => folder(entry) === root || folder(entry).startsWith(root + "/"))) return;
  if (statSync(transcript).size > 64 * 1024 * 1024) return;
  const text = readFileSync(transcript, "utf8");
  const steps = [];
  for (const line of text.split("\n")) {
    if (line === "") continue;
    try {
      steps.push(JSON.parse(line));
    } catch {}
  }
  const typed = (step) => step !== undefined && step !== null && step.source === "USER_EXPLICIT" && step.type === "USER_INPUT";
  // A conversation of the creator opens with what they typed; a sub-agent's opens with a system message.
  if (!typed(steps[0]) || steps[0].step_index !== 0) return;
  const dir = storeDir();
  const file = join(dir, sha256(conversation).slice(0, 32) + ".jsonl");
  const known = recordedSteps(file);
  const now = Date.now();
  // Only the step that opens this model call: the last one of the transcript. A message another
  // process appended earlier (a session an agent resumed with agy -p --conversation) is followed by
  // the steps of that process, so it never is the last; the creator's own is.
  const last = steps[steps.length - 1];
  // Each step once: a repeated index (the first line counts) or a negative one is not a step.
  const taken = new Set();
  const fresh = steps.filter((step) => {
    if (step !== last) return false;
    if (!typed(step) || step.status !== "DONE" || !Number.isInteger(step.step_index) || step.step_index < 0) return false;
    if (known.has(step.step_index) || taken.has(step.step_index)) return false;
    taken.add(step.step_index);
    return typeof step.content === "string" && typeof step.created_at === "string";
  });
  const lines = [];
  for (const step of fresh) {
    const body = requestBody(step.content);
    const message = body === undefined ? undefined : creatorText(seen(body));
    const normalised = message === undefined ? "" : normalize(message);
    const at = Date.parse(step.created_at);
    if (normalised === "" || !Number.isFinite(at) || at > now + 60000 || now - at > RETENTION_MS) continue;
    lines.push({ v: 1, session: conversation, project: ROOT, at: new Date(at).toISOString(), digest: sha256(normalised), text: normalised.slice(0, MAX_TEXT), step: step.step_index });
  }
  if (lines.length === 0) return;
  mkdirSync(dir, { recursive: true, mode: 0o700 });
  prune(dir, file, now);
  for (const line of lines) appendFileSync(file, JSON.stringify(line) + "\n", { mode: 0o600 });
}

function preInvocation(stdin) {
  let conversation = "";
  try {
    const input = JSON.parse(stdin);
    const id = typeof input.conversationId === "string" ? input.conversationId.trim() : "";
    if (/^[0-9a-f-]{8,64}$/i.test(id)) conversation = id;
    if (conversation !== "") record(input, conversation);
  } catch {}
  if (conversation === "") answer({});
  const context = "${SESSION_CONTEXT_PREFIX}" + conversation + " (pass it as session to chat.answer)";
  answer({ injectSteps: [{ ephemeralMessage: context }] });
}

const event = process.argv[2] ?? "";
let stdin = "";
try {
  stdin = readFileSync(0, "utf8");
} catch {}
if (event === "pre-tool") preTool(stdin);
else if (event === "post-tool") postTool(stdin);
else if (event === "pre-invocation") preInvocation(stdin);
else answer({});
`;
}
