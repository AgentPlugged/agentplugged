import { CHAT_RETENTION_MS } from "@agentplugged/protocol";
import type { McpServerLaunch } from "../sync/mcp.js";
import { chatStoreHelpers, GENERATED_HEADER_SLASH, SESSION_CONTEXT_PREFIX } from "./prompt-hook.js";

/**
 * The Antigravity CLI hooks of the project plugin, in one generated script without
 * dependency. Antigravity runs the plugin's `hooks.json` handlers as `command` hooks (the only type
 * it has) and sends each a JSON object on its standard input; a handler answers in JSON.
 *
 * - `pre-tool` (`PreToolUse`): the permission rules of the product. The script asks the engine
 *   (`agentplugged hook antigravity pre-tool`), which applies the same rule lists as Claude Code's
 *   `.claude/settings.json` and the same gate as `guard.check`. It fails closed: Antigravity
 *   itself denies a tool when its hook fails, and the script answers `deny` when the engine cannot
 *   be reached (an `{}` answer is a denial too, so the script always names a decision).
 * - `post-tool` (`PostToolUse`): records a read of external content (`guard.external_read`).
 * - `pre-invocation` (`PreInvocation`): the proof of the chat. Antigravity has no hook on the
 *   message the creator types, but it gives every hook the path of the conversation's transcript.
 *   The script reads it and records, in the store of the machine (`~/.agentplugged/chat/`, the
 *   store Claude Code's hook writes), the messages the creator typed and nothing else: a step whose
 *   `source` is `USER_EXPLICIT` and whose `type` is `USER_INPUT`, in a conversation whose first step
 *   is such a step (a sub-agent's conversation starts with a system message), in a transcript that
 *   lives where Antigravity writes it, for a workspace of the project. Only the transcript is the
 *   filter: the script asks the system nothing (no walk up the processes: it cost seconds, up to
 *   tens of seconds under load, and a message lost to its timeout). A session an agent starts with
 *   `agy -p` writes the same steps: the transcript carries nothing that tells print mode apart, so
 *   such a message is recorded too, in the journal, like any other (the trace, not the
 *   blocking). What a hook injects (`userMessage`), what
 *   `schedule` fires and what an agent sends come with another `source` and are never recorded. It
 *   also tells the agent the session id to pass to `chat.answer`. It never blocks a model
 *   call: any failure is ignored. A choice made in `ask_question` comes back as a tool result of the
 *   model's step, never as a message of the creator: it is not recorded.
 *
 * Agents may not run the script nor write the plugin (`sync` denies `node …agentplugged-antigravity…`
 * and writes under `.agents/`), the store, or the transcripts.
 */

