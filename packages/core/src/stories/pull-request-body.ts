import {
  MAX_PULL_REQUEST_CRITERIA,
  type PullRequestTestStatus,
  STORY_SECTIONS,
} from "@agentplugged/protocol";
import type { ParsedDocument } from "../docs/parse-document.js";
import { type ForgeRepository, repositoryWebUrl } from "./story-forge.js";

/**
 * The fixed template of a story's pull request, as pure functions: the
 * acceptance criteria of a story, its cost, and the title and text `core` renders the same way
 * every time, without a clock nor chance. English, like the method's content.
 */

/** The line that opens every text the engine renders: the next update rewrites the text. */
export const PULL_REQUEST_MARKER =
  "<!-- Generated by agentplugged from the approved story: edit the story, not this text. The next update rewrites it. -->";

/** The longest a criterion is shown. */
const CRITERION_MAX = 1000;

const LIST_ITEM = /^ {0,3}(?:[-*+]|\d{1,9}[.)])[ \t]+(.*)$/;
const FENCE = /^ {0,3}(?:`{3,}|~{3,})/;
const CHECKBOX = /^\[[ xX]\][ \t]+/;

function clean(text: string): string {
  const flat = text.replace(CHECKBOX, "").replace(/\s+/g, " ").trim();
  return flat.length <= CRITERION_MAX ? flat : `${flat.slice(0, CRITERION_MAX - 1).trimEnd()}…`;
}

/**
 * The acceptance criteria of a story, in order: the items of the top-level list of its
 * `## Acceptance criteria` section (a checkbox already there is dropped), or, without a list, its
 * paragraphs. Code blocks are skipped. At most `MAX_PULL_REQUEST_CRITERIA`.
 */
export function acceptanceCriteria(document: ParsedDocument): string[] {
  const { items, paragraphs } = readCriteria(document);
  return (items.length > 0 ? items : paragraphs).slice(0, MAX_PULL_REQUEST_CRITERIA);
}

/**
 * The criteria written as a list, one per item, as the story template writes them:
 * the only ones the engine follows one by one. Prose is not split into criteria it could number.
 */
export function listedCriteria(document: ParsedDocument): string[] {
  return readCriteria(document).items.slice(0, MAX_PULL_REQUEST_CRITERIA);
}

function readCriteria(document: ParsedDocument): { items: string[]; paragraphs: string[] } {
  const titles: readonly string[] = STORY_SECTIONS.acceptance_criteria;
  const section = document.sections.find((candidate) => titles.includes(candidate.title));
  if (section === undefined) return { items: [], paragraphs: [] };
  const items: string[] = [];
  const paragraphs: string[] = [];
  let item: string | undefined;
  let paragraph: string | undefined;
  let fenced = false;
  let blank = false;
  /** The indentation of the section's first list item: deeper items are nested, not criteria. */
  let topIndent: number | undefined;
  const endItem = () => {
    if (item !== undefined && clean(item) !== "") items.push(clean(item));
    item = undefined;
  };
  const endParagraph = () => {
    if (paragraph !== undefined && clean(paragraph) !== "") paragraphs.push(clean(paragraph));
    paragraph = undefined;
  };
  for (const line of section.lines) {
    if (FENCE.test(line)) {
      fenced = !fenced;
      endItem();
      endParagraph();
      continue;
    }
    if (fenced) continue;
    if (line.trim() === "") {
      endParagraph();
      blank = true;
      continue;
    }
    const indent = line.length - line.trimStart().length;
    const listed = LIST_ITEM.exec(line.slice(Math.max(0, indent - 3)));
    const nested = listed !== null && topIndent !== undefined && indent > topIndent;
    if (listed !== null && !nested) {
      topIndent ??= indent;
      endItem();
      endParagraph();
      item = listed[1] ?? "";
    } else if (item !== undefined && (nested || indent > 0 || !blank)) {
      // A nested item, or the item's own text going on: part of the criterion above.
      item = `${item} ${(listed?.[1] ?? line).trim()}`;
    } else {
      endItem();
      paragraph = paragraph === undefined ? line.trim() : `${paragraph} ${line.trim()}`;
    }
    blank = false;
  }
  endItem();
  endParagraph();
  return { items, paragraphs };
}

/** What the text of a story's pull request is rendered from. */
export interface PullRequestContent {
  readonly story: {
    readonly id: string;
    readonly title: string;
    /** The story's file, relative to the repository's top, with `/`. */
    readonly path: string;
    /** The Git blob of the version the creator approved. */
    readonly blob: string;
    readonly requirements: readonly string[];
  };
  readonly repository: ForgeRepository;
  readonly branch: string;
  readonly base: string;
  /** The commit pushed. */
  readonly head: string;
  readonly criteria: ReadonlyArray<{ readonly text: string; readonly checked: boolean }>;
  readonly tests: { readonly status: PullRequestTestStatus; readonly summary?: string | undefined };
}

/** The heading of the cost section older pull requests carry (no text shows a cost any more). */
export const COST_HEADING = "## Cost";

/**
 * The text without the cost section older pull requests carry: what `body_sha256` is computed on,
 * so that a digest recorded still matches.
 */
export function withoutCost(body: string): string {
  const normalized = body.replace(/\r\n/g, "\n");
  const at = normalized.lastIndexOf(`\n${COST_HEADING}\n`);
  return at === -1 ? normalized : normalized.slice(0, at + 1);
}

/** The web address of a file at a commit, on GitHub or GitLab. */
export function fileWebUrl(repository: ForgeRepository, commit: string, path: string): string {
  const encoded = path
    .split("/")
    .map((segment) => encodeURIComponent(segment))
    .join("/");
  const blob = repository.forge === "gitlab" ? "-/blob" : "blob";
  return `${repositoryWebUrl(repository)}/${blob}/${commit}/${encoded}`;
}

const TEST_LINES: Readonly<Record<PullRequestTestStatus, string>> = {
  passed: "**Passed**",
  failed: "**Failed**",
  not_run: "**Not run**",
  not_reported: "**Not reported by the agent**",
};

/** The title of a story's pull request: `<title> (<id>)`, at most 256 characters. */
export function pullRequestTitle(id: string, title: string): string {
  const suffix = ` (${id})`;
  const flat = title.replace(/\s+/g, " ").trim();
  const room = 256 - suffix.length;
  const cut = flat.length <= room ? flat : `${flat.slice(0, room - 1).trimEnd()}…`;
  return `${cut}${suffix}`;
}

/**
 * The text of a story's pull request, always in the same order: the marker, the story (id, title,
 * link to its file at the commit pushed, approved version, branch and target), its requirements,
 * its acceptance criteria as checkboxes and the tests. It shows no cost.
 */
export function renderPullRequestBody(content: PullRequestContent): string {
  const { story, tests } = content;
  const link = fileWebUrl(content.repository, content.head, story.path);
  const summary = tests.summary?.replace(/\s+/g, " ").trim();
  const lines = [
    PULL_REQUEST_MARKER,
    "",
    "## Story",
    "",
    `**${story.id} — ${story.title.replace(/\s+/g, " ").trim()}**`,
    "",
    `- Story: [${story.path}](${link}) (approved version \`${story.blob.slice(0, 12)}\`)`,
    `- Branch: \`${content.branch}\` into \`${content.base}\` at \`${content.head.slice(0, 12)}\``,
    "",
    "## Requirements",
    "",
    ...(story.requirements.length === 0
      ? ["None listed."]
      : story.requirements.map((requirement) => `- ${requirement}`)),
    "",
    "## Acceptance criteria",
    "",
    ...(content.criteria.length === 0
      ? ["None found in the story."]
      : content.criteria.map(({ text, checked }) => `- [${checked ? "x" : " "}] ${text}`)),
    "",
    "## Tests",
    "",
    summary === undefined || summary === ""
      ? TEST_LINES[tests.status]
      : `${TEST_LINES[tests.status]}: ${summary}`,
    "",
  ];
  return lines.join("\n");
}
