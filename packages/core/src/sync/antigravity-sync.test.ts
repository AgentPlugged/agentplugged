import { describe, expect, it } from "vitest";
import { hookLaunch } from "../chat/antigravity-hook.js";
import {
  ANTIGRAVITY_HOOK_PATH,
  ANTIGRAVITY_HOOKS_PATH,
  ANTIGRAVITY_MCP_CONFIG_PATH,
  ANTIGRAVITY_PLUGIN_DIR,
  ANTIGRAVITY_POLICY_PATH,
  COMPATIBILITY,
  type CommandContext,
  claudeRulePermissions,
  DEFAULT_RULES,
  initCommand,
  resolveProfile,
  type SyncResult,
  syncCommand,
  type ToolProbe,
} from "../index.js";
import { MemoryFiles, shippedMethod } from "../testing/memory-files.js";
import { ANTIGRAVITY_DECISIONS_REASON, ANTIGRAVITY_PLUGIN_KEPT_REASON } from "./compatibility.js";
import { SYNC_MANIFEST_PATH } from "./manifest.js";

/**
 * Antigravity CLI reads MCP servers and hooks from a plugin only. `sync` writes
 * `.agents/plugins/agentplugged/` and takes back the `.agents/mcp_config.json` it wrote before.
 */

const NO_TOOL: ToolProbe = {
  which: async () => undefined,
  version: async () => undefined,
  extensions: async () => [],
};

function context(files: MemoryFiles, platform = "linux"): CommandContext {
  return {
    files,
    tools: NO_TOOL,
    method: shippedMethod(),
    actor: "human",
    engineVersion: "1.0.0",
    platform,
  };
}

async function installed(initial: Record<string, string> = {}): Promise<MemoryFiles> {
  const files = new MemoryFiles(initial);
  const result = await initCommand.run(context(files), { profile: resolveProfile("new-product") });
  if (!result.ok) throw new Error(`init failed: ${result.error.code}`);
  return files;
}

async function sync(files: MemoryFiles, platform = "linux"): Promise<SyncResult> {
  const result = await syncCommand.run(context(files, platform), {});
  if (!result.ok) throw new Error(`sync failed: ${result.error.code}`);
  return result.value;
}

const CONFIG = ".agentplugged/method.yaml";
const MANIFEST = ".agents/plugins/agentplugged/plugin.json";
const LEGACY = ".agents/mcp_config.json";
const PLUGIN_FILES = [
  MANIFEST,
  ANTIGRAVITY_MCP_CONFIG_PATH,
  ANTIGRAVITY_HOOKS_PATH,
  ANTIGRAVITY_POLICY_PATH,
  ANTIGRAVITY_HOOK_PATH,
];

function setTools(files: MemoryFiles, tools: readonly string[]) {
  const text = (files.files.get(CONFIG) ?? "").replace(/tools:\n(?: {2}- .*\n)+/, "");
  files.seed(CONFIG, `${text}tools: [${tools.join(", ")}]\n`);
}

const json = (files: MemoryFiles, path: string) => JSON.parse(files.files.get(path) ?? "null");
const action = (result: SyncResult, path: string) =>
  result.entries.find((entry) => entry.path === path)?.action;

describe("sync: Antigravity CLI's project plugin", () => {
  it("writes the plugin, and no longer the MCP file Antigravity ignored", async () => {
    const files = await installed();
    const result = await sync(files);
    expect(ANTIGRAVITY_PLUGIN_DIR).toBe(".agents/plugins/agentplugged");
    for (const path of PLUGIN_FILES) {
      expect(action(result, path), path).toBe("created");
      expect(result.entries.find((entry) => entry.path === path)?.group).toBe("antigravity");
    }
    expect(files.files.has(LEGACY)).toBe(false);
    expect(json(files, MANIFEST)).toEqual({
      name: "agentplugged",
      description: "Generated by agentplugged. Do not edit: changes are overwritten.",
    });
    // The same server and launcher as the other tools.
    expect(json(files, ANTIGRAVITY_MCP_CONFIG_PATH)).toEqual({
      mcpServers: {
        agentplugged: { command: "npx", args: ["-y", "agentplugged@1.0.0", "mcp"] },
      },
    });
    // Still the agents, the skills and GEMINI.md.
    for (const path of [".agents/agents/iris.md", ".agents/skills/iris/SKILL.md", "GEMINI.md"]) {
      expect(files.files.has(path), path).toBe(true);
    }
  });

  it("declares the hooks: the rules before a tool, the reads after it, the chat before a model call", async () => {
    const files = await installed();
    await sync(files);
    const hooks = json(files, ANTIGRAVITY_HOOKS_PATH).agentplugged;
    const command = (event: string) => `node hooks/agentplugged-antigravity.mjs ${event}`;
    expect(hooks.PreToolUse).toEqual([
      { matcher: "*", hooks: [{ type: "command", command: command("pre-tool"), timeout: 30 }] },
    ]);
    expect(hooks.PostToolUse).toEqual([
      { matcher: "*", hooks: [{ type: "command", command: command("post-tool"), timeout: 30 }] },
    ]);
    // `PreInvocation` is flat: handlers directly, without a matcher group.
    expect(hooks.PreInvocation).toEqual([
      { type: "command", command: command("pre-invocation"), timeout: 30 },
    ]);
    expect(Object.keys(hooks).sort()).toEqual(["PostToolUse", "PreInvocation", "PreToolUse"]);
    // The script is a generated file of ours, with the engine's launch and no dependency.
    const script = files.files.get(ANTIGRAVITY_HOOK_PATH) ?? "";
    expect(script.startsWith("// Generated by agentplugged. Do not edit")).toBe(true);
    expect(script).toContain('"command":"npx","args":["-y","agentplugged@1.0.0"]');
    expect(script).not.toContain('"mcp"]');
    expect(script.match(/^import .* from "[^n]|require\(/m)).toBeNull();
  });

  it("writes the rules the hook applies: the lists of Claude Code's settings, never an allow", async () => {
    const files = await installed();
    await sync(files);
    const policy = json(files, ANTIGRAVITY_POLICY_PATH);
    const claude = json(files, ".claude/settings.json").permissions;
    expect(policy.version).toBe(1);
    expect(policy.rules).toEqual(DEFAULT_RULES);
    expect(Object.keys(policy)).not.toContain("allow");
    // Every deny and ask rule of Claude Code's settings, the creator's commands included.
    // (The PowerShell twins and the escaped final backslash are Claude Code's spelling only.)
    const mirrored = (rules: string[]) =>
      rules.filter((rule) => !rule.startsWith("PowerShell(") && !rule.endsWith("\\)"));
    expect(policy.deny).toEqual(expect.arrayContaining(mirrored(claude.deny)));
    expect(policy.ask).toEqual(mirrored(claude.ask ?? []));
    expect(policy.deny).toEqual(
      expect.arrayContaining([
        "Edit(/.agentplugged/method.yaml)",
        "Edit(/.agents/**)",
        "Edit(~/.gemini/config/**)",
        "Edit(**/.system_generated/**)",
        "Bash(agy *)",
        "Bash(gh pr merge*)",
        "Bash(git push)",
        "Bash(node *agentplugged-antigravity*)",
      ]),
    );
    // The same functions that write Claude Code's lists wrote these.
    const expected = claudeRulePermissions(DEFAULT_RULES, undefined);
    expect(policy.ask).toEqual(expected.ask);
    expect(policy.deny).toEqual(expect.arrayContaining([...expected.deny]));
  });

  it("follows the creator's rules, and the creator's own launch of method.yaml", async () => {
    const files = await installed();
    files.seed(
      CONFIG,
      `${files.files.get(CONFIG)}rules:\n  internet: deny\nmcp:\n  command: node\n  args: [/work/bin.js, mcp]\n`,
    );
    const result = await sync(files, "win32");
    expect(result.warnings).toEqual([{ kind: "local_engine", path: CONFIG }]);
    expect(json(files, ANTIGRAVITY_POLICY_PATH).rules.internet).toBe("deny");
    expect(json(files, ANTIGRAVITY_POLICY_PATH).deny).toContain("Bash(curl*)");
    expect(json(files, ANTIGRAVITY_MCP_CONFIG_PATH).mcpServers.agentplugged).toEqual({
      command: "node",
      args: ["/work/bin.js", "mcp"],
    });
    // The hook starts the engine the same way, without `mcp`.
    expect(files.files.get(ANTIGRAVITY_HOOK_PATH)).toContain(
      '"command":"node","args":["/work/bin.js"]',
    );
  });

  it("starts the engine for the hook without the server's own arguments", async () => {
    // The creator's own launch: what follows `mcp` (`--engine-any`) is the server's option.
    expect(hookLaunch({ command: "node", args: ["/work/bin.js", "mcp", "--engine-any"] })).toEqual({
      command: "node",
      args: ["/work/bin.js"],
    });
    expect(hookLaunch({ command: "npx", args: ["-y", "agentplugged@1.0.0", "mcp"] })).toEqual({
      command: "npx",
      args: ["-y", "agentplugged@1.0.0"],
    });
    expect(hookLaunch({ command: "agentplugged", args: [] })).toEqual({
      command: "agentplugged",
      args: [],
    });
  });

  it("wraps npx in cmd /c on Windows, for the server and for the hook", async () => {
    const files = await installed();
    await sync(files, "win32");
    expect(json(files, ANTIGRAVITY_MCP_CONFIG_PATH).mcpServers.agentplugged).toEqual({
      command: "cmd",
      args: ["/c", "npx", "-y", "agentplugged@1.0.0", "mcp"],
    });
    expect(files.files.get(ANTIGRAVITY_HOOK_PATH)).toContain(
      '"command":"cmd","args":["/c","npx","-y","agentplugged@1.0.0"]',
    );
  });

  it("changes nothing when run again, and follows the pinned version", async () => {
    const files = await installed();
    await sync(files);
    files.writes.length = 0;
    const again = await sync(files);
    expect(again.entries.every((entry) => entry.action === "unchanged")).toBe(true);
    expect(files.writes).toEqual([]);
    files.seed(
      CONFIG,
      (files.files.get(CONFIG) ?? "").replace("engine_version: 1.0.0", "engine_version: 1.2.0"),
    );
    const bumped = await sync(files);
    for (const path of [ANTIGRAVITY_MCP_CONFIG_PATH, ANTIGRAVITY_HOOK_PATH]) {
      expect(action(bumped, path), path).toBe("updated");
      expect(files.files.get(path), path).toContain("agentplugged@1.2.0");
    }
  });

  it("regenerates a file edited by hand and says so", async () => {
    const files = await installed();
    await sync(files);
    files.seed(ANTIGRAVITY_HOOKS_PATH, '{ "agentplugged": {} }\n');
    files.seed(
      ANTIGRAVITY_HOOK_PATH,
      "// Generated by agentplugged. Do not edit: changes are overwritten.\nprocess.exit(0);\n",
    );
    const result = await sync(files);
    expect(result.warnings).toContainEqual({ kind: "overwritten", path: ANTIGRAVITY_HOOKS_PATH });
    expect(result.warnings).toContainEqual({ kind: "overwritten", path: ANTIGRAVITY_HOOK_PATH });
    expect(json(files, ANTIGRAVITY_HOOKS_PATH).agentplugged.PreToolUse).toBeDefined();
  });

  it("takes back the MCP file it wrote before, and only its entry", async () => {
    const files = await installed();
    await sync(files);
    // A project synchronised by the engine: its entry in the file Antigravity ignores.
    const entry = { command: "npx", args: ["-y", "agentplugged@1.0.0", "mcp"] };
    files.seed(LEGACY, `${JSON.stringify({ mcpServers: { agentplugged: entry } }, null, 2)}\n`);
    const manifest = json(files, SYNC_MANIFEST_PATH);
    manifest.settings = {
      ...manifest.settings,
      [LEGACY]: { created: true, keys: ["mcpServers", "mcpServers.agentplugged"] },
    };
    files.seed(SYNC_MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`);
    const result = await sync(files);
    expect(action(result, LEGACY)).toBe("deleted");
    expect(files.files.has(LEGACY)).toBe(false);
    expect(json(files, SYNC_MANIFEST_PATH).settings?.[LEGACY]).toBeUndefined();

    // With other servers of the creator's in it, only ours goes.
    files.seed(
      LEGACY,
      `${JSON.stringify({ mcpServers: { docs: { command: "docs" }, agentplugged: entry } }, null, 2)}\n`,
    );
    const again = json(files, SYNC_MANIFEST_PATH);
    again.settings = {
      ...again.settings,
      [LEGACY]: { created: false, keys: ["mcpServers.agentplugged"] },
    };
    files.seed(SYNC_MANIFEST_PATH, `${JSON.stringify(again, null, 2)}\n`);
    await sync(files);
    expect(json(files, LEGACY)).toEqual({ mcpServers: { docs: { command: "docs" } } });
  });

  it("never touches a creator's own .agents/mcp_config.json", async () => {
    const own = `${JSON.stringify({ mcpServers: { agentplugged: { command: "mine" } } })}\n`;
    const files = await installed({ [LEGACY]: own });
    const result = await sync(files);
    expect(files.files.get(LEGACY)).toBe(own);
    expect(action(result, LEGACY)).toBeUndefined();
    expect(result.warnings).toEqual([]);
  });

  it("leaves a plugin folder of the creator's as it is, and says so", async () => {
    const mine = '{ "name": "agentplugged", "description": "my own plugin" }\n';
    const files = await installed({ [MANIFEST]: mine });
    const result = await sync(files);
    expect(result.warnings).toContainEqual({
      kind: "conflict",
      path: `${ANTIGRAVITY_PLUGIN_DIR}/`,
    });
    expect(files.files.get(MANIFEST)).toBe(mine);
    for (const path of PLUGIN_FILES.filter((entry) => entry !== MANIFEST)) {
      expect(files.files.has(path), path).toBe(false);
    }
    // Agents, skills and GEMINI.md are written all the same.
    expect(files.files.has(".agents/agents/iris.md")).toBe(true);
  });

  it("deletes the plugin when Antigravity leaves the list, and keeps a file edited by hand", async () => {
    const files = await installed();
    await sync(files);
    files.seed(ANTIGRAVITY_POLICY_PATH, `${files.files.get(ANTIGRAVITY_POLICY_PATH)} `);
    setTools(files, ["claude-code"]);
    const result = await sync(files);
    for (const path of PLUGIN_FILES.filter((entry) => entry !== ANTIGRAVITY_POLICY_PATH)) {
      expect(action(result, path), path).toBe("deleted");
      expect(files.files.has(path), path).toBe(false);
    }
    expect(result.warnings).toContainEqual({ kind: "kept", path: ANTIGRAVITY_POLICY_PATH });
    expect(files.files.has(ANTIGRAVITY_POLICY_PATH)).toBe(true);
    expect(files.dirs.has(`${ANTIGRAVITY_PLUGIN_DIR}/hooks`)).toBe(false);
  });

  it("is protected from the agents by the permission rules of every targeted tool", async () => {
    const files = await installed();
    await sync(files);
    expect(json(files, ".claude/settings.json").permissions.deny).toEqual(
      expect.arrayContaining([
        "Edit(/.agents/**)",
        "Bash(agy *)",
        "Bash(node *agentplugged-antigravity*)",
      ]),
    );
    expect(json(files, ".cursor/cli.json").permissions.deny).toEqual(
      expect.arrayContaining(["Write(.agents/**)", "Shell(agy:*)"]),
    );
  });
});

describe("compatibility: Antigravity CLI", () => {
  const cells = COMPATIBILITY.find((entry) => entry.client === "antigravity")?.cells;

  it("enforces the rules, the reads and the proof of the chat through the plugin", () => {
    for (const capability of ["permissions", "rules", "untrusted", "installs"] as const) {
      expect(cells?.[capability].support, capability).toBe("native");
      expect(cells?.[capability].files, capability).toEqual([
        ANTIGRAVITY_HOOKS_PATH,
        ANTIGRAVITY_POLICY_PATH,
        ANTIGRAVITY_HOOK_PATH,
      ]);
    }
    expect(cells?.mcp).toEqual({ support: "native", files: [ANTIGRAVITY_MCP_CONFIG_PATH] });
  });

  it("makes the proof of the chat native, and keeps the forms and the developers' own working copies as fallbacks, and says why", () => {
    // The hook reads the transcript, seen in an interactive session on 2026-10-05.
    expect(cells?.chat_proof.support).toBe("native");
    expect(cells?.chat_proof.files).toEqual([
      ANTIGRAVITY_HOOKS_PATH,
      ANTIGRAVITY_POLICY_PATH,
      ANTIGRAVITY_HOOK_PATH,
    ]);
    expect(cells?.decisions.support).toBe("fallback");
    expect(cells?.decisions.reason).toBe(ANTIGRAVITY_DECISIONS_REASON);
    expect(ANTIGRAVITY_DECISIONS_REASON).toContain("non-interactive mode");
    expect(cells?.isolation.support).toBe("fallback");
  });

  it("announces only those in the constitution", async () => {
    const files = await installed();
    const result = await sync(files);
    expect(result.fallbacks.filter((f) => f.client === "antigravity").map((f) => f.id)).toEqual([
      "antigravity.isolation",
      "antigravity.decisions",
    ]);
    const constitution = files.reference();
    expect(constitution).toContain("- Antigravity CLI, decisions: ");
    expect(constitution).not.toContain("- Antigravity CLI, chat_proof: ");
    expect(constitution).not.toContain("- Antigravity CLI, permissions: ");
  });

  it("says what is not written when the plugin's folder is the creator's: every capability it brings is a fallback", async () => {
    const files = await installed({
      [MANIFEST]: '{ "name": "agentplugged", "description": "my own plugin" }\n',
    });
    const result = await sync(files);
    const ids = result.fallbacks.filter((f) => f.client === "antigravity").map((f) => f.id);
    expect(ids).toEqual([
      "antigravity.permissions.plugin-kept",
      "antigravity.mcp.plugin-kept",
      "antigravity.rules.plugin-kept",
      "antigravity.untrusted.plugin-kept",
      "antigravity.chat_proof.plugin-kept",
      "antigravity.isolation",
      "antigravity.decisions",
      "antigravity.installs.plugin-kept",
    ]);
    expect(result.fallbacks.find((f) => f.id === "antigravity.mcp.plugin-kept")?.reason).toBe(
      ANTIGRAVITY_PLUGIN_KEPT_REASON,
    );
  });
});
