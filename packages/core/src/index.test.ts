import { describe, expect, it } from "vitest";
import {
  BLOCK_BEGIN,
  type CommandContext,
  createCommandRegistry,
  fallbacksFor,
  GENERATED_HEADER,
  type InitEntry,
  initCommand,
  METHOD_SUBDIRS,
  MemoryKeyStore,
  MemoryStateStore,
  packageName,
  pointerBlock,
  renderConstitution,
  type ToolProbe,
  type WorkspaceFiles,
  withEngineCommand,
} from "./index.js";
import { MemoryFiles, SHIPPED_MODELS, shippedMethod } from "./testing/memory-files.js";

const ENGINE = "1.2.3";
/** `product_id` init creates in these tests. */
const PRODUCT_ID = "01JZ3333333333333333333333";

/** Without any tool found, init targets the five tools: their fallbacks are in the constitution. */
const CONSTITUTION = withEngineCommand(
  renderConstitution(fallbacksFor(["claude-code", "codex", "antigravity", "cursor", "kimi"])),
  `npx -y agentplugged@${"1.2.3"}`,
);

/** A machine without any AI tool. */
const noTools: ToolProbe = {
  which: async () => undefined,
  version: async () => undefined,
  extensions: async () => [],
};

function context(files: WorkspaceFiles, tools: ToolProbe = noTools): CommandContext {
  return {
    files,
    tools,
    method: shippedMethod(),
    actor: "human",
    engineVersion: ENGINE,
    newId: () => PRODUCT_ID,
  };
}

async function init(files: MemoryFiles): Promise<InitEntry[]> {
  const result = await initCommand.run(context(files), {});
  if (!result.ok) throw new Error(`init failed: ${result.error.code}`);
  return [...result.value.entries];
}

function actionOf(entries: InitEntry[], path: string) {
  return entries.find((entry) => entry.path === path)?.action;
}

const count = (text: string, needle: string) => text.split(needle).length - 1;

describe("core", () => {
  it("exposes its package name", () => {
    expect(packageName).toBe("@agentplugged/core");
  });

  it("registers init and rejects unknown commands", async () => {
    const registry = createCommandRegistry();
    expect(registry.names()).toEqual([
      "init",
      "profile",
      "sync",
      "agent",
      "journal",
      "review",
      "key",
      "trust",
      "docs",
      "history",
      "next",
      "rules",
      "migrate",
      "deferred",
      "story",
      "ci",
      "tests",
      "trace",
      "usage",
      "publication",
      "doctor",
    ]);
    const result = await registry.run("nope", context(new MemoryFiles()));
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.toPayload()).toEqual({
        code: "UNKNOWN_COMMAND",
        message_key: "error.unknown_command",
        details: { command: "nope" },
      });
    }
  });
});

describe("init", () => {
  it("installs the method in a new repository", async () => {
    const files = new MemoryFiles();
    const entries = await init(files);

    expect(entries.every((entry) => entry.action === "created")).toBe(true);
    expect(entries.map((entry) => entry.path)).toEqual([
      ".agentplugged/",
      ...METHOD_SUBDIRS.map((name) => `.agentplugged/${name}/`),
      ".agentplugged/.gitignore",
      ".agentplugged/profile.md",
      ".agentplugged/agents/iris/",
      ".agentplugged/models.yaml",
      ".agentplugged/method.yaml",
      "AGENTS.md",
      ...[...files.files.keys()].filter((path) => path.startsWith(".agentplugged/reference/")),
    ]);
    // The reference is one file per section.
    expect(files.files.has(".agentplugged/reference/reporting.md")).toBe(true);
    expect(files.files.has(".agentplugged/REFERENCE.md")).toBe(false);
    // The model table is copied as a generated file.
    expect(files.files.get(".agentplugged/models.yaml")).toBe(
      `# Generated by agentplugged. Do not edit: changes are overwritten.
${SHIPPED_MODELS}`,
    );
    for (const name of METHOD_SUBDIRS) {
      expect(files.files.get(`.agentplugged/${name}/.gitkeep`)).toBe("");
    }
    expect(files.files.get(".agentplugged/.gitignore")).toMatch(
      /^# Generated.*\n\.cache\/\noverrides\/skills\/\*\.local\.yaml\n$/,
    );
    expect(files.files.get(".agentplugged/method.yaml")).toBe(
      `format_version: 2\nengine_version: ${ENGINE}\nproduct_id: ${PRODUCT_ID}\ntools:\n  - claude-code\n  - codex\n  - antigravity\n  - cursor\n  - kimi\n`,
    );
    const agents = files.files.get("AGENTS.md") ?? "";
    expect(agents.startsWith(`${GENERATED_HEADER}\n`)).toBe(true);
    expect(agents).toBe(CONSTITUTION);
    expect(files.files.has(".agentplugged/AGENTS.md")).toBe(false);
    expect(files.files.has("CLAUDE.md")).toBe(false);
    expect(files.files.has("GEMINI.md")).toBe(false);
    expect(files.files.has(".gitignore")).toBe(false);
  });

  it("keeps a creator's AGENTS.md and writes the constitution under .agentplugged/", async () => {
    const mine = "# My rules\r\nBe nice.";
    const files = new MemoryFiles({ "AGENTS.md": mine });
    const entries = await init(files);

    const agents = files.files.get("AGENTS.md") ?? "";
    expect(agents.startsWith(mine)).toBe(true);
    expect(agents).toBe(
      `${mine}\r\n\r\n${BLOCK_BEGIN}\r\nThis project uses the AgentPlugged method. Read and follow \`.agentplugged/AGENTS.md\`.\r\n<!-- agentplugged:end -->\r\n`,
    );
    expect(files.files.get(".agentplugged/AGENTS.md")).toBe(CONSTITUTION);
    expect(actionOf(entries, "AGENTS.md")).toBe("updated");
    expect(actionOf(entries, ".agentplugged/AGENTS.md")).toBe("created");

    await init(files);
    expect(count(files.files.get("AGENTS.md") ?? "", BLOCK_BEGIN)).toBe(1);
  });

  it("adds the block to existing CLAUDE.md and GEMINI.md once, and never creates them", async () => {
    const files = new MemoryFiles({ "CLAUDE.md": "claude\n" });
    const entries = await init(files);

    expect(files.files.get("CLAUDE.md")).toBe(`claude\n\n${pointerBlock("AGENTS.md", "import")}\n`);
    expect(actionOf(entries, "CLAUDE.md")).toBe("updated");
    expect(files.files.has("GEMINI.md")).toBe(false);
    expect(actionOf(entries, "GEMINI.md")).toBeUndefined();

    files.seed("GEMINI.md", "");
    const again = await init(files);
    expect(actionOf(again, "CLAUDE.md")).toBe("unchanged");
    expect(actionOf(again, "GEMINI.md")).toBe("updated");
    expect(files.files.get("GEMINI.md")?.startsWith(BLOCK_BEGIN)).toBe(true);
    expect(count(files.files.get("CLAUDE.md") ?? "", BLOCK_BEGIN)).toBe(1);
  });

  it("does not add a second block when the markers are already present", async () => {
    const claude = `intro\n${pointerBlock("AGENTS.md", "import")}\nmore`;
    const files = new MemoryFiles({ "CLAUDE.md": claude });
    const entries = await init(files);
    expect(files.files.get("CLAUDE.md")).toBe(claude);
    expect(actionOf(entries, "CLAUDE.md")).toBe("unchanged");
  });

  it("rewrites only the block content when the constitution has moved", async () => {
    const files = new MemoryFiles({ "AGENTS.md": "mine\n", "CLAUDE.md": "intro\r\n" });
    await init(files);
    expect(files.files.get("CLAUDE.md")).toContain("\r\n@.agentplugged/AGENTS.md\r\n");

    // The creator drops their AGENTS.md: the constitution moves to the root.
    files.files.delete("AGENTS.md");
    files.seed("CLAUDE.md", `${files.files.get("CLAUDE.md")}outro\r\n`);
    const entries = await init(files);

    expect(actionOf(entries, "CLAUDE.md")).toBe("updated");
    expect(files.files.get("CLAUDE.md")).toBe(
      `intro\r\n\r\n${pointerBlock("AGENTS.md", "import").replace(/\n/g, "\r\n")}\r\noutro\r\n`,
    );
    expect(files.files.get("AGENTS.md")).toBe(CONSTITUTION);

    files.writes.length = 0;
    expect(actionOf(await init(files), "CLAUDE.md")).toBe("unchanged");
    expect(files.writes).toEqual([]);
  });

  it("treats a generated AGENTS.md with a byte-order mark as unchanged", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.seed("AGENTS.md", `﻿${CONSTITUTION}`);
    files.writes.length = 0;
    const entries = await init(files);
    expect(actionOf(entries, "AGENTS.md")).toBe("unchanged");
    expect(files.writes).toEqual([]);
    expect(files.files.has(".agentplugged/AGENTS.md")).toBe(false);
  });

  it("leaves a generated CLAUDE.md alone (it belongs to sync)", async () => {
    const claude = `${GENERATED_HEADER}\nimported`;
    const files = new MemoryFiles({ "CLAUDE.md": claude });
    await init(files);
    expect(files.files.get("CLAUDE.md")).toBe(claude);
  });

  it("modifies nothing when run again on an installed method", async () => {
    const files = new MemoryFiles({ "AGENTS.md": "mine\n", "CLAUDE.md": "claude\n" });
    await init(files);
    files.seed(
      ".agentplugged/method.yaml",
      `# tuned by hand\nformat_version: 2\nengine_version: ${ENGINE}\nproduct_id: ${PRODUCT_ID}\n`,
    );
    files.seed(".agentplugged/docs/prd.md", "prd");
    files.seed(".agentplugged/stories/1-1.md", "story");
    files.seed(".agentplugged/overrides/dev.md", "override");
    const before = files.snapshot();
    files.writes.length = 0;

    const entries = await init(files);
    expect(entries.every((entry) => entry.action === "unchanged")).toBe(true);
    expect(files.writes).toEqual([]);
    expect(files.snapshot()).toEqual(before);
  });

  it("adds product_id to a method.yaml from before the journal, keeping its comments", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.seed(
      ".agentplugged/method.yaml",
      "# mine\r\nformat_version: 2\r\nengine_version: 1.2.3\r\n",
    );
    const result = await initCommand.run(context(files), {});
    if (!result.ok) throw new Error(result.error.code);
    expect(result.value.productIdAdded).toBe(PRODUCT_ID);
    expect(actionOf([...result.value.entries], ".agentplugged/method.yaml")).toBe("updated");
    expect(files.files.get(".agentplugged/method.yaml")).toBe(
      `# mine\r\nformat_version: 2\r\nengine_version: 1.2.3\r\nproduct_id: ${PRODUCT_ID}\r\n`,
    );
    const again = await initCommand.run(context(files), {});
    expect(again.ok && again.value.productIdAdded).toBeUndefined();
  });

  it("upgrades the engine and adds product_id in one write", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.seed(".agentplugged/method.yaml", "# mine\nformat_version: 2\nengine_version: 0.0.9\n");
    const result = await initCommand.run(context(files), { upgrade_engine: true });
    if (!result.ok) throw new Error(result.error.code);
    expect(files.files.get(".agentplugged/method.yaml")).toBe(
      `# mine\nformat_version: 2\nengine_version: ${ENGINE}\nproduct_id: ${PRODUCT_ID}\n`,
    );
    expect(result.value.engineUpgrade).toEqual({ from: "0.0.9", to: ENGINE });
    expect(result.value.productIdAdded).toBe(PRODUCT_ID);
  });

  it("adopts the product id of the journal, and refuses a different one", async () => {
    const journal = new MemoryStateStore({ keys: new MemoryKeyStore(), allowTestTypes: true });
    const held = "01JZ4444444444444444444444";
    await journal.append({
      type: "test.appended",
      actor: { kind: "system" },
      product: held,
      provenance: "trusted",
      payload: {},
    });
    const files = new MemoryFiles();
    const created = await initCommand.run({ ...context(files), journal }, {});
    expect(created.ok).toBe(true);
    expect(files.files.get(".agentplugged/method.yaml")).toContain(`\nproduct_id: ${held}\n`);

    const other = new MemoryFiles();
    await init(other);
    other.writes.length = 0;
    const refused = await initCommand.run({ ...context(other), journal }, {});
    expect(refused.ok).toBe(false);
    if (!refused.ok) {
      expect(refused.error.toPayload()).toEqual({
        code: "PRODUCT_ID_MISMATCH",
        message_key: "error.product_id_mismatch",
        details: { product_id: PRODUCT_ID, journal_product_id: held },
      });
    }
    expect(other.writes).toEqual([]);
  });

  it("keeps a generated AGENTS.md with CRLF line endings as is", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.seed("AGENTS.md", CONSTITUTION.replace(/\n/g, "\r\n"));
    files.writes.length = 0;
    const entries = await init(files);
    expect(actionOf(entries, "AGENTS.md")).toBe("unchanged");
    expect(files.writes).toEqual([]);
  });

  it("refreshes an outdated generated file", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.seed("AGENTS.md", `${GENERATED_HEADER}\nold constitution\n`);
    files.seed(
      ".agentplugged/.gitignore",
      "# Generated by agentplugged. Do not edit: changes are overwritten.\n",
    );
    const entries = await init(files);
    expect(actionOf(entries, "AGENTS.md")).toBe("updated");
    expect(actionOf(entries, ".agentplugged/.gitignore")).toBe("updated");
    expect(files.files.get("AGENTS.md")).toBe(CONSTITUTION);
  });

  it("never rewrites a creator's .agentplugged/.gitignore", async () => {
    const files = new MemoryFiles({ ".agentplugged/.gitignore": "mine\n" });
    const entries = await init(files);
    expect(files.files.get(".agentplugged/.gitignore")).toBe("mine\n");
    expect(actionOf(entries, ".agentplugged/.gitignore")).toBe("unchanged");
  });

  it("recreates a deleted folder and a missing .gitkeep", async () => {
    const files = new MemoryFiles();
    await init(files);
    files.removeDir(".agentplugged/epics");
    files.files.delete(".agentplugged/docs/.gitkeep");
    const entries = await init(files);
    expect(actionOf(entries, ".agentplugged/epics/")).toBe("created");
    expect(actionOf(entries, ".agentplugged/docs/")).toBe("updated");
    expect(actionOf(entries, ".agentplugged/stories/")).toBe("unchanged");
    expect(files.files.has(".agentplugged/epics/.gitkeep")).toBe(true);
    expect(files.files.has(".agentplugged/docs/.gitkeep")).toBe(true);
  });

  it.each([
    ["format_version: x\nengine_version: 1.0.0\n", "format_version", 1],
    ['format_version: 2\nengine_version: "1.0"\n', "engine_version", 2],
    ["format_version: 2\n", "engine_version", undefined],
    ["format_version: 2\nengine_version: 1.0.0\nextra: true\n", "extra", 3],
    ["- 1\n", "(root)", 1],
    ["", "(root)", undefined],
  ])("rejects an invalid method.yaml %j without writing anything", async (yaml, field, line) => {
    const files = new MemoryFiles({ ".agentplugged/method.yaml": yaml, "AGENTS.md": "mine" });
    const before = files.snapshot();
    const result = await initCommand.run(context(files), {});

    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error.code).toBe("METHOD_CONFIG_INVALID");
    expect(result.error.details.field).toBe(field);
    expect(result.error.details.line).toBe(line);
    expect(result.error.message_key).toBe(
      line === undefined ? "error.method_config_invalid" : "error.method_config_invalid.line",
    );
    expect(files.writes).toEqual([]);
    expect(files.snapshot()).toEqual(before);
  });

  it("rejects unreadable YAML with its line", async () => {
    const files = new MemoryFiles({
      ".agentplugged/method.yaml": "format_version: 2\nengine_version: [1.0.0\n",
    });
    const result = await initCommand.run(context(files), {});
    expect(result.ok).toBe(false);
    if (result.ok) return;
    expect(result.error.toPayload()).toMatchObject({
      code: "METHOD_CONFIG_INVALID",
      message_key: "error.method_config_invalid.line",
      details: { path: ".agentplugged/method.yaml", field: "(root)" },
    });
    expect(typeof result.error.details.line).toBe("number");
    expect(files.writes).toEqual([]);
  });

  it("detects the AI tools after installing, and installs even without any", async () => {
    const files = new MemoryFiles();
    const result = await initCommand.run(context(files), {});
    expect(result.ok).toBe(true);
    if (!result.ok) return;
    expect(result.value.tools.map((tool) => [tool.id, tool.found])).toEqual([
      ["claude-code", false],
      ["codex", false],
      ["antigravity", false],
      ["cursor", false],
      ["kimi", false],
    ]);
    expect(files.files.has("AGENTS.md")).toBe(true);

    const probed: string[] = [];
    const claude: ToolProbe = {
      which: async (names) => {
        probed.push(...names);
        return names.includes("claude") ? { name: "claude", path: "/bin/claude" } : undefined;
      },
      version: async () => "2.1.287 (Claude Code)",
      extensions: async () => [],
    };
    const again = await initCommand.run(context(files, claude), {});
    expect(again.ok && again.value.tools[0]?.version).toBe("2.1.287");
    expect(probed).toContain("claude");
  });

  it("does not probe the tools when method.yaml is invalid", async () => {
    let probed = false;
    const spy: ToolProbe = {
      which: async () => {
        probed = true;
        return undefined;
      },
      version: async () => undefined,
      extensions: async () => [],
    };
    const files = new MemoryFiles({ ".agentplugged/method.yaml": "nope: 1\n" });
    const result = await initCommand.run(context(files, spy), {});
    expect(result.ok).toBe(false);
    expect(probed).toBe(false);
  });

  it("reports a method.yaml that cannot be read", async () => {
    const files = new MemoryFiles();
    files.dirs.add(".agentplugged");
    files.dirs.add(".agentplugged/method.yaml");
    const result = await initCommand.run(context(files), {});
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.error.details.field).toBe("(root)");
    expect(files.writes).toEqual([]);
  });
});
