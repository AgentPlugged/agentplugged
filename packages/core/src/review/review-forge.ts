import type { ForgeId, ReviewKind } from "@agentplugged/protocol";
import type { CommandContext } from "../command.js";
import type { StoryState } from "../projection/agent-reducers.js";
import { deliveryRemote, oneLine } from "../stories/pull-request.js";
import {
  type ForgeLineComment,
  type ForgeRepository,
  type ForgeReviewDraft,
  forgeRepositoryOf,
  type StoryForge,
} from "../stories/story-forge.js";
import type { DiffFile, ReviewFindingState, ReviewPass, ReviewRecord } from "./review-rules.js";

/**
 * The forge's side of a review: each review of a closed pass posted on the story's
 * pull request, a comment on its line for each finding on a changed line, the others in the
 * review's text; and a deviation posted as a comment. Posted by the engine with the forge's tool
 * the creator logged in, never by an agent. The text is in English, like the pull request's.
 */

/** The first line of a text the engine posts: who wrote it. */
export const REVIEW_MARKER = "<!-- Generated by agentplugged (review) -->";
export const DEVIATION_MARKER = "<!-- Generated by agentplugged (deviation) -->";

/**
 * An agent's text made inert before the engine posts it with the creator's login: no mention
 * (`@team`), no command a bot reads at a line's start (`/approve`), no image (an address that
 * would leak what loads it), no HTML comment (a forged marker).
 */
export function forgeText(text: string): string {
  return text
    .replace(/<!--/g, "&lt;!--")
    .replace(/@(?=[\w-])/g, "@\u200b")
    .replace(/!\[/g, "!\\[")
    .replace(/^(\s*)([/!])/gm, "$1\\$2");
}

/** A path in a code span: its backquotes cannot close it. */
function codePath(path: string): string {
  return path.replaceAll("`", "'");
}

/** What happened on the forge: posted, nothing to post there (`skipped`), or the tool failed. */
export type ForgePosting =
  | { readonly status: "posted"; readonly forge: ForgeId; readonly pr: number }
  | {
      readonly status: "skipped";
      readonly reason: "no_pull_request" | "not_linked" | "no_forge";
    }
  | { readonly status: "failed"; readonly message: string };

/** The pull request of a story and its repository, or why nothing can be posted. */
export async function forgeTarget(
  context: CommandContext,
  story: StoryState | undefined,
): Promise<
  | { readonly forge: StoryForge; readonly repository: ForgeRepository; readonly number: number }
  | Extract<ForgePosting, { status: "skipped" | "failed" }>
> {
  const pr = story?.pull_request;
  const started = story?.started;
  if (pr === undefined || started === undefined) {
    return { status: "skipped", reason: "no_pull_request" };
  }
  const forge = context.storyForge;
  if (forge === undefined) return { status: "skipped", reason: "no_forge" };
  try {
    const inspection = await forge.inspect(started.branch, started.base);
    if (!inspection.repository) return { status: "skipped", reason: "not_linked" };
    const remote = deliveryRemote(inspection.remotes, started.base_ref);
    if (remote === undefined) return { status: "skipped", reason: "not_linked" };
    const located = forgeRepositoryOf(remote.url);
    if (!("forge" in located) || located.forge !== pr.forge) {
      return { status: "skipped", reason: "not_linked" };
    }
    if ((await forge.cli(located)) !== "ready") return { status: "skipped", reason: "not_linked" };
    return { forge, repository: located, number: pr.number };
  } catch (error) {
    return {
      status: "failed",
      message: oneLine(error instanceof Error ? error.message : String(error)),
    };
  }
}

const SEVERITY_LABELS = {
  blocking: "Blocking",
  should_fix: "Should fix",
  minor: "Minor",
} as const;

const VERDICT_LABELS = {
  pass: "pass",
  pass_with_reservations: "pass with reservations",
  fail: "fail",
} as const;

const KIND_LABELS: Readonly<Record<ReviewKind, string>> = {
  qa: "QA review",
  security: "Security review",
};

/** A finding as one line comment: severity, title, detail, and its id. */
function commentBody(finding: ReviewFindingState): string {
  const detail = finding.detail === undefined ? "" : `\n\n${forgeText(finding.detail)}`;
  return `**${SEVERITY_LABELS[finding.severity]}** — ${forgeText(finding.title)}${detail}\n\n<sub>${finding.id}</sub>`;
}

/** A finding outside the diff's lines, as an item of the review's text. */
function noteLine(finding: ReviewFindingState): string {
  const where =
    finding.path === undefined
      ? ""
      : ` \`${finding.path}${finding.line === undefined ? "" : `:${finding.line}`}\``;
  const detail = finding.detail === undefined ? "" : `\n  ${finding.detail.replace(/\n/g, "\n  ")}`;
  return `- **${SEVERITY_LABELS[finding.severity]}**${where} — ${finding.title} (${finding.id})${detail}`;
}

/** What the pass says of its security review, for the QA review's text. */
function securityNote(pass: ReviewPass): string {
  const { reasons, unavailable } = pass.security;
  if (reasons.length === 0) return "Security review: not needed for this story.";
  if (unavailable === true) {
    return `Security review: needed (${reasons.join(", ")}), but no security reviewer is active.`;
  }
  return `Security review: needed (${reasons.join(", ")}).`;
}

/** The draft of one review: comments on the lines of the diff, the other findings in the text. */
export function reviewDraft(
  pass: ReviewPass,
  review: ReviewRecord,
  diff: readonly DiffFile[],
  /** False: every finding in the text (the forge refused a line of the review). */
  inline = true,
): { draft: ForgeReviewDraft; comments: number; notes: number } {
  const comments: ForgeLineComment[] = [];
  const notes: string[] = [];
  for (const finding of review.findings) {
    const file =
      finding.path === undefined ? undefined : diff.find((entry) => entry.path === finding.path);
    const line = finding.line;
    if (inline && file !== undefined && line !== undefined && file.lines.has(line)) {
      comments.push({
        path: file.path,
        old_path: file.old_path ?? file.path,
        line,
        old_line: file.lines.get(line) ?? null,
        body: commentBody(finding),
      });
    } else {
      notes.push(noteLine(finding));
    }
  }
  const sections = [
    REVIEW_MARKER,
    `## ${KIND_LABELS[review.kind]}, pass ${pass.number}: ${VERDICT_LABELS[review.verdict]}`,
    forgeText(review.summary),
    ...(review.kind === "qa" ? [securityNote(pass)] : []),
    ...(notes.length === 0 ? [] : ["### Findings outside the changed lines", notes.join("\n")]),
    `<sub>${review.id} · commit ${pass.commit.slice(0, 12)} · ${review.findings.length} finding(s)</sub>`,
  ];
  return {
    draft: { commit: pass.commit, body: sections.join("\n\n"), comments },
    comments: comments.length,
    notes: notes.length,
  };
}

/** The text of a deviation's comment. */
export function deviationComment(deviation: {
  readonly id: string;
  readonly requirements: readonly string[];
  readonly summary: string;
  readonly detail?: string | undefined;
  readonly commit?: string | undefined;
}): string {
  return [
    DEVIATION_MARKER,
    `## Deviation ${deviation.id} from ${deviation.requirements.join(", ")}`,
    forgeText(deviation.summary),
    ...(deviation.detail === undefined ? [] : [forgeText(deviation.detail)]),
    `<sub>${deviation.commit === undefined ? "" : `commit ${deviation.commit.slice(0, 12)} · `}lifted by the agent that reported it once fixed (\`lift_deviation\`), or by the creator.</sub>`,
  ].join("\n\n");
}
