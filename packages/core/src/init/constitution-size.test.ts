describe("no safety rule is lost by shortening AGENTS.md", () => {
  it.each(SAFETY_IN_SHORT)("keeps %s in AGENTS.md", (rule) => {
    expect(flat(short).toLowerCase()).toContain(flat(rule).toLowerCase());
  });

  it.each(DETAIL_IN_REFERENCE)("keeps %s somewhere: AGENTS.md or the reference", (rule) => {
    expect(flat(`${short}\n${reference}`).toLowerCase()).toContain(flat(rule).toLowerCase());
  });

  it("keeps every numbered rule of the constitution's seven in both files", () => {
    for (const text of [short, reference]) {
      expect(text).toContain("## Rules");
      for (let n = 1; n <= 7; n++) expect(text, `rule ${n}`).toContain(`\n${n}. `);
    }
  });

  it("keeps the permission rules in force in AGENTS.md, in short, and in full in the reference", () => {
    expect(short).toContain("## Permission rules");
    expect(short).toContain("deny: destructive_command, push_main, force_push, read_secrets");
    expect(reference).toContain("- `push_main` (push to the main branch): deny (never do it)");
  });
});
