import { TOOL_IDS } from "@agentplugged/protocol";
import { describe, expect, it } from "vitest";
import { DEFAULT_RULES } from "../index.js";
import { fallbacksFor } from "../sync/compatibility.js";
import {
  referenceNameOf,
  renderConstitution,
  renderConstitutionReference,
  renderConstitutionReferenceFiles,
} from "./constitution.js";
import { REFERENCE_DIR } from "./layout.js";

// A project like the creator's test project: every tool, Noah installed, the default rules.
const fallbacks = fallbacksFor([...TOOL_IDS]);
const assistant = { tools: [...TOOL_IDS] };
const short = renderConstitution(fallbacks, DEFAULT_RULES, assistant);
const reference = renderConstitutionReference(fallbacks, DEFAULT_RULES, assistant);
const files = renderConstitutionReferenceFiles(fallbacks, DEFAULT_RULES, assistant);
const flat = (text: string) => text.replace(/\s+/g, " ");

const KIB = 1024;
/** Size in UTF-8 bytes. */
const bytes = (text: string) =>
  [...text].reduce((sum, char) => {
    const code = char.codePointAt(0) ?? 0;
    return sum + (code < 0x80 ? 1 : code < 0x800 ? 2 : code < 0x10000 ? 3 : 4);
  }, 0);

describe("AGENTS.md stays short", () => {
  it("weighs at most 6 000 characters with every tool and every function", () => {
    expect(short.length).toBeLessThanOrEqual(6_000);
  });

  it("tells Noah he may be started without a head, and to launch the sub-agents himself", () => {
    const text = flat(reference);
    expect(text).toContain("You may be started without a head");
    expect(text).toContain("launch the sub-agents yourself");
    expect(flat(renderConstitution())).not.toContain("without a head");
  });

  it("is also short without Noah and without fallbacks", () => {
    expect(renderConstitution().length).toBeLessThanOrEqual(5_500);
  });

  it("sends to the reference, one file per section, and names each of them", () => {
    expect(short).toContain(`\`${REFERENCE_DIR}/\``);
    expect(bytes(reference)).toBeGreaterThan(60 * KIB);
    for (const title of [
      "Talking with the creator",
      "Main session: Noah",
      "Reporting",
      "Checkpoints in the chat",
      "Rules for skills and agents",
      "Stacks to validate",
      "Points of validation",
      "The journey is proposed, never imposed",
      "Git workflow: the creator's, not the method's",
      "Creator's decisions in the chat",
      "Installing dependencies",
      "Deliverables to publish",
      "Phases",
      "Sensitive content",
      "Memory",
      "Knowledge base",
      "Permission rules",
      "Tool fallbacks",
    ]) {
      expect(reference, title).toContain(`\n## ${title}\n`);
      const name = referenceNameOf(title);
      const file = files.find((f) => f.path === `${REFERENCE_DIR}/${name}.md`);
      expect(file, title).toBeDefined();
      expect(file?.content, title).toContain(`## ${title}\n`);
      expect(short, title).toContain(`\`${name}\``);
    }
  });

  it("writes a file for every tool, and no file is left without a title or a header", () => {
    for (const tool of ["state", "checkpoint", "chat", "story", "review", "agent", "guard"]) {
      expect(files.map((f) => f.path)).toContain(`${REFERENCE_DIR}/tool-${tool}.md`);
    }
    for (const file of files) {
      expect(file.content, file.path).toMatch(/^<!-- Generated by agentplugged/);
      expect(file.content, file.path).toMatch(/^## /m);
    }
    // Together the files hold the whole reference: the same sections, the same text.
    const together = flat(files.map((f) => f.content).join("\n"));
    for (const heading of reference.match(/^## .+$/gm) ?? []) {
      expect(together, heading).toContain(flat(heading));
    }
  });

  it("does not announce a section the reference does not have", () => {
    const bare = renderConstitution();
    expect(bare).not.toContain("`noah`: if you are Noah");
    expect(bare).not.toContain("`fallbacks`");
    expect(renderConstitutionReference()).not.toContain("## Tool fallbacks");
    expect(renderConstitutionReferenceFiles().map((f) => f.path)).not.toContain(
      `${REFERENCE_DIR}/fallbacks.md`,
    );
  });
});

