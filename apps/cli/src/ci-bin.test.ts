import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { mkdir, mkdtemp, readFile, realpath, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { Readable } from "node:stream";
import { NodeKeyStore } from "@agentplugged/adapters-git";
import { removeTestKeys } from "@agentplugged/adapters-git/test-keychain";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { main } from "./main.js";

vi.setConfig({ testTimeout: 120_000 });

/** A keychain service of this file only, deleted after each test: never the real entries. */
const service = `agentplugged-test-ci-bin-${process.pid}-${Date.now()}`;
const VERSION = (
  JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as {
    version: string;
  }
).version;

let parent: string;
let home: string;
let env: Record<string, string>;

function gitOk(cwd: string, args: string[]): string {
  const result = spawnSync("git", args, { cwd, encoding: "utf8", env, windowsHide: true });
  if (result.status !== 0) throw new Error(`git ${args.join(" ")}: ${result.stderr}`);
  return result.stdout.trim();
}

/** True when this machine has a system keychain (a Linux server may have none). */
async function keychainAvailable(): Promise<boolean> {
  try {
    await new NodeKeyStore({ service }).readHumanSecret();
    return true;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (/platform secure storage|no storage access|secret service|dbus|keyutils/i.test(message)) {
      return false;
    }
    throw error;
  }
}

beforeEach(async (context) => {
  if (!(await keychainAvailable())) context.skip("no system keychain on this machine");
  parent = await realpath(await mkdtemp(join(tmpdir(), "agentplugged-ci-bin-")));
  home = await mkdtemp(join(tmpdir(), "agentplugged-ci-bin-home-"));
  await writeFile(join(home, ".gitconfig"), "");
  const inherited: Record<string, string> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (value !== undefined && !/^(home|userprofile)$/i.test(key)) inherited[key] = value;
  }
  env = {
    ...inherited,
    HOME: home,
    USERPROFILE: home,
    AGENTPLUGGED_LANG: "en",
    AGENTPLUGGED_KEYCHAIN_SERVICE: service,
    AGENTPLUGGED_PRESENCE: "none",
    AGENTPLUGGED_ENVIRONMENT: "none",
    GIT_CEILING_DIRECTORIES: await realpath(tmpdir()),
    GIT_CONFIG_NOSYSTEM: "1",
    GIT_CONFIG_GLOBAL: join(home, ".gitconfig"),
    GIT_TERMINAL_PROMPT: "0",
  };
});

afterEach(async () => {
  await removeTestKeys(service);
  for (const folder of [parent, home]) {
    if (folder !== undefined) {
      await rm(folder, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
    }
  }
});

/** A product in its own repository (Ada's identity), the method installed by `init`. */
async function repository(name: string): Promise<string> {
  const cwd = join(parent, name);
  await mkdir(cwd);
  gitOk(cwd, ["init", "-q", "-b", "main"]);
  gitOk(cwd, ["config", "user.name", "Ada"]);
  gitOk(cwd, ["config", "user.email", "ada@example.com"]);
  gitOk(cwd, ["config", "core.autocrlf", "false"]);
  await writeFile(
    join(cwd, "package.json"),
    JSON.stringify({ packageManager: "npm@10.9.0", scripts: { lint: "x", test: "y" } }),
  );
  const init = await cli(cwd, ["init", "--profile", "new-product"]);
  if (init.status !== 0) throw new Error(`init failed: ${init.stderr}`);
  return cwd;
}

async function cli(cwd: string, args: string[]) {
  let stdout = "";
  let stderr = "";
  const status = await main({
    argv: args,
    cwd,
    env: { ...env, PATH: process.env.PATH ?? "" },
    engineVersion: VERSION,
    stdout: (text) => {
      stdout += text;
    },
    stderr: (text) => {
      stderr += text;
    },
    stdin: Readable.from([]),
    interactive: false,
  });
  return { status, stdout, stderr };
}

describe("ci setup, end to end", () => {
  it("writes GitHub's workflow for an origin on github.com, then never again", async () => {
    const cwd = await repository("shop");
    gitOk(cwd, ["remote", "add", "origin", "git@github.com:acme/shop.git"]);
    const first = await cli(cwd, ["ci", "setup"]);
    expect(first.status, first.stderr).toBe(0);
    expect(first.stdout).toContain("Base CI written to .github/workflows/ci.yml (github, npm)");
    expect(first.stdout).toContain('build: add a "build" script to package.json');
    const text = await readFile(join(cwd, ".github/workflows/ci.yml"), "utf8");
    expect(text).toContain("Generated by agentplugged (setup-ci)");
    expect(text).toContain("timeout-minutes:");
    expect(text).toContain("- run: 'npm run lint'");
    const again = await cli(cwd, ["ci", "setup"]);
    expect(again.status).toBe(0);
    expect(again.stdout).toBe(
      "The product already has a CI (.github/workflows/ci.yml): nothing was written.\n",
    );
  });

  it("writes GitLab's with --forge when no remote says it, and refuses a misplaced option", async () => {
    const cwd = await repository("shop-lab");
    const none = await cli(cwd, ["ci", "setup"]);
    expect(none.status).toBe(1);
    expect(none.stderr).toContain("CI_UNAVAILABLE");
    const lab = await cli(cwd, ["ci", "setup", "--forge", "gitlab"]);
    expect(lab.status, lab.stderr).toBe(0);
    expect(lab.stdout).toContain("Base CI written to .gitlab-ci.yml (gitlab, npm)");
    expect(await readFile(join(cwd, ".gitlab-ci.yml"), "utf8")).toContain("image: node:lts");
    for (const args of [
      ["next", "--forge", "github"],
      ["story", "start", "1-1", "--forge", "github"],
      ["next", "--waive", "no CI"],
      ["story", "start", "1-1", "--waive", "no CI"],
    ]) {
      const refused = await cli(cwd, args);
      expect(refused.status, args.join(" ")).toBe(1);
      expect(refused.stderr).toContain("INVALID_ARGUMENTS");
    }
    // The waiver is the creator's, at a terminal only.
    const waive = await cli(cwd, ["story", "ci", "1-1", "--waive", "No CI here."]);
    expect(waive.status).toBe(1);
    expect(waive.stderr).toContain("REVIEW_NOT_INTERACTIVE");
  });
});

describe("tests setup, end to end", () => {
  it("proposes the command of the criteria for the product's stack, once, and refuses misplaced options", async () => {
    const cwd = await repository("shop-tests");
    await writeFile(
      join(cwd, "package.json"),
      JSON.stringify({
        packageManager: "npm@10.9.0",
        dependencies: { react: "19" },
        devDependencies: { vitest: "3" },
      }),
    );
    const first = await cli(cwd, ["tests", "setup"]);
    expect(first.status, first.stderr).toBe(0);
    expect(first.stdout).toContain("proposal written to .agentplugged/proofs.yaml");
    expect(first.stdout).toContain("unit and API: vitest (found in the product)");
    expect(first.stdout).toContain(
      "end to end: playwright (proposed, to check against the architecture)",
    );
    expect(first.stdout).toContain(
      "to install (npm), through the validation of installations: npm install --save-dev @playwright/test",
    );
    const proposal = await readFile(join(cwd, ".agentplugged/proofs.yaml"), "utf8");
    expect(proposal).toContain(
      "npx vitest run -t {criterion} --passWithNoTests && npx playwright test -g {criterion} --pass-with-no-tests",
    );
    const again = await cli(cwd, ["tests", "setup", "--e2e", "none"]);
    expect(again.status).toBe(0);
    expect(again.stdout).toContain("already declares a command that runs the tests of a criterion");
    expect(await readFile(join(cwd, ".agentplugged/proofs.yaml"), "utf8")).toBe(proposal);
    for (const args of [
      ["tests"],
      ["tests", "run"],
      ["tests", "setup", "x"],
      ["tests", "setup", "--runner", "nope"],
      ["next", "--runner", "vitest"],
      ["ci", "setup", "--e2e", "none"],
    ]) {
      const refused = await cli(cwd, args);
      expect(refused.status, args.join(" ")).toBe(1);
      expect(refused.stderr).toContain("INVALID_ARGUMENTS");
    }
  });

  it("tells which tests an existing CI does not run, and writes nothing", async () => {
    const cwd = await repository("shop-gaps");
    await writeFile(
      join(cwd, "package.json"),
      JSON.stringify({ packageManager: "npm@10.9.0", scripts: { test: "y", "test:e2e": "z" } }),
    );
    await mkdir(join(cwd, ".github/workflows"), { recursive: true });
    await writeFile(join(cwd, ".github/workflows/ci.yml"), "jobs: {}\n");
    const result = await cli(cwd, ["ci", "setup"]);
    expect(result.status, result.stderr).toBe(0);
    expect(result.stdout).toContain("nothing was written.");
    expect(result.stdout).toContain('Not checked by the CI: test: the CI does not run "test:e2e"');
    expect(await readFile(join(cwd, ".github/workflows/ci.yml"), "utf8")).toBe("jobs: {}\n");
  });
});
