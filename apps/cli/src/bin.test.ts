/** Dotfiles and editor backups are never part of a skill. */
const ignored = (name: string) => name.startsWith(".") || /(?:~|\.bak|\.orig|\.swp)$/.test(name);
function noahReferences(root: string): Record<string, string> {
  const folder = join(methodSourceDir, "agents", "noah", "references");
  return Object.fromEntries(
    readdirSync(folder)
      .filter((name) => !ignored(name))
      .map((name) => [`${root}/noah/references/${name}`, "created"]),
  );
}
function shippedSkills(): Map<string, string[]> {
  if (skillsCache !== undefined) return skillsCache;
  const root = resolve(dirname(bin), "method/skills");
  if (!existsSync(root)) throw new Error(`${root} is missing: build the CLI first`);
  const skills = new Map<string, string[]>();
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    if (!entry.isDirectory() || ignored(entry.name)) continue;
    const folder = join(root, entry.name);
    // What `sync` renders: `SKILL.md`, and the files of `assets/`, `references/` and `scripts/`.
    const files = readdirSync(folder, { recursive: true, withFileTypes: true })
      .filter((file) => file.isFile() && !ignored(file.name))
      .map((file) => relative(folder, join(file.parentPath, file.name)).replaceAll("\\", "/"))
      .filter((file) => file === "SKILL.md" || /^(assets|references|scripts)\//.test(file))
      .sort();
    skills.set(entry.name, files);
  }
  if (skills.size === 0) throw new Error(`${root} holds no skill: build the CLI first`);
  // The build ships exactly the skills of the method's sources.
  const sources = readdirSync(join(methodSourceDir, "skills"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => entry.name)
    .sort();
  if (JSON.stringify([...skills.keys()].sort()) !== JSON.stringify(sources)) {
    throw new Error(`${root} is out of date (sources: ${sources.join(", ")}): build the CLI again`);
  }
  skillsCache = skills;
  return skills;
}

