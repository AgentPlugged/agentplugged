/**
 * True when this machine has a system keychain (a Linux machine without a running Secret Service
 * has none): without one, the binary must say so instead of creating the creator's keys.
 */
async function keychainAvailable(): Promise<boolean> {
  try {
    await new NodeKeyStore({
      service: process.env.AGENTPLUGGED_TEST_KEYCHAIN_SERVICE ?? "agentplugged-test-cli-probe",
    }).readHumanSecret();
    return true;
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (/platform secure storage|no storage access|secret service|dbus|keyutils/i.test(message)) {
      return false;
    }
    throw error;
  }
}
