function run(args: string[], lang = "en") {
  const env: Record<string, string | undefined> = {};
  for (const [key, value] of Object.entries(process.env)) {
    if (!/^(path|home|userprofile)$/i.test(key)) env[key] = value;
  }
  const result = spawnSync(process.execPath, [bin, ...args], {
    cwd,
    encoding: "utf8",
    env: { ...env, PATH: path, HOME: home, USERPROFILE: home, AGENTPLUGGED_LANG: lang },
    timeout: 90_000,
  });
  return { status: result.status, stdout: result.stdout, stderr: result.stderr };
}

/** `path -> label` from the summary printed by init, which ends at the first blank line. */
function summary(stdout: string): Map<string, string> {
  const map = new Map<string, string>();
  const lines = stdout.split("\n");
  const end = lines.indexOf("");
  for (const line of lines.slice(1, end === -1 ? undefined : end)) {
    const match = /^ {2}(.+?) {2,}(\S+)$/.exec(line);
    if (match?.[1] && match[2]) map.set(match[2], match[1].trim());
  }
  return map;
}

/** Content and modification time of every file, `.git` excluded. */
async function fingerprint(): Promise<Map<string, string>> {
  const result = new Map<string, string>();
  async function walk(dir: string) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.name === ".git") continue;
      if (entry.isDirectory()) await walk(path);
      else {
        const [content, info] = await Promise.all([readFile(path), stat(path)]);
        result.set(relative(cwd, path), `${info.mtimeMs}:${content.toString("base64")}`);
      }
    }
  }
  await walk(cwd);
  return result;
}

