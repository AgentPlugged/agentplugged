describe("agentplugged journal sync", () => {
  /** The temporary bare repository standing for the remote. */
  let remote: string;
  const saved: Record<string, string | undefined> = {};

  /** Runs git in a test repository; never in this one, never on the network. */
  function git(dir: string, args: string[]): string {
    const result = spawnSync("git", args, { cwd: dir, encoding: "utf8", windowsHide: true });
    if (result.status !== 0) throw new Error(`git ${args.join(" ")}: ${result.stderr}`);
    return result.stdout.trim();
  }

  function identify(dir: string) {
    git(dir, ["config", "user.name", "Ada"]);
    git(dir, ["config", "user.email", "ada@example.com"]);
  }

  /** A journal with `count` events, written with a key held in memory (never the keychain). */
  async function appendEvents(dir: string, count: number) {
    const journal = new GitStateStore({
      allowTestTypes: true,
      cwd: dir,
      keys: new MemoryKeyStore("AQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQEBAQE"),
      machineLockPath: join(home, "machine-key.lock"),
    });
    try {
      for (let n = 0; n < count; n++) {
        await journal.append({
          type: "test.appended",
          actor: { kind: "system" },
          product: "01JZ0000000000000000000000",
          provenance: "trusted",
          payload: { n },
        });
      }
    } finally {
      journal.close();
    }
  }

  beforeEach(async () => {
    // Git finds no repository above the temporary folders, and no configuration of this machine.
    const env = {
      GIT_CEILING_DIRECTORIES: await realpath(tmpdir()),
      GIT_CONFIG_NOSYSTEM: "1",
      GIT_CONFIG_GLOBAL: join(home, ".gitconfig"),
    };
    for (const [key, value] of Object.entries(env)) {
      saved[key] = process.env[key];
      process.env[key] = value;
    }
    await writeFile(join(home, ".gitconfig"), "");
    // The binary must find git.
    path = process.env.PATH ?? "";
    remote = await mkdtemp(join(tmpdir(), "agentplugged-remote-"));
    git(remote, ["init", "-q", "--bare", "-b", "main"]);
    git(cwd, ["init", "-q", "-b", "main"]);
    identify(cwd);
  });

  afterEach(async () => {
    for (const [key, value] of Object.entries(saved)) {
      if (value === undefined) delete process.env[key];
      else process.env[key] = value;
    }
    await rm(remote, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
  });

  it("creates the remote branch, then says up to date, in English and French", async () => {
    git(cwd, ["remote", "add", "origin", remote]);
    await appendEvents(cwd, 1);
    const first = run(["journal", "sync"]);
    expect(first.stderr).toBe("");
    expect(first.status).toBe(0);
    expect(first.stdout).toBe(
      "Journal synchronized with origin\n  received: 0\n  sent: 3 (branch agentplugged/journal created on origin)\n",
    );
    expect(git(remote, ["rev-parse", "refs/heads/agentplugged/journal"])).toBe(
      git(cwd, ["rev-parse", "refs/heads/agentplugged/journal"]),
    );
    expect(run(["journal", "sync"]).stdout).toBe("Journal already up to date with origin.\n");
    expect(run(["journal", "sync", "--remote", "origin"], "fr").stdout).toBe(
      "Journal déjà à jour avec origin.\n",
    );

    // Another machine, a clone: it receives the 3 events by fast-forward.
    const other = await mkdtemp(join(tmpdir(), "agentplugged-other-"));
    const mine = cwd;
    try {
      git(other, ["clone", "-q", remote, "."]);
      identify(other);
      cwd = other;
      const received = run(["journal", "sync"], "fr");
      expect(received.stderr).toBe("");
      expect(received.stdout).toBe(
        "Journal synchronisé avec origin\n  reçus : 3 (avance rapide)\n  envoyés : 0\n",
      );
      expect(git(other, ["rev-parse", "refs/heads/agentplugged/journal"])).toBe(
        git(remote, ["rev-parse", "refs/heads/agentplugged/journal"]),
      );
    } finally {
      cwd = mine;
      await rm(other, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
    }
  });

  it("gives NO_REMOTE without a remote, and refuses misplaced arguments", async () => {
    await appendEvents(cwd, 1);
    const none = run(["journal", "sync"]);
    expect(none.status).toBe(1);
    expect(none.stdout).toBe("");
    expect(none.stderr).toBe(
      "Error NO_REMOTE: No Git remote is configured: the journal syncs through one. Add one with `git remote add origin <url>`, then run `npx agentplugged journal sync` again. Nothing was done.\n",
    );
    const named = run(["journal", "sync", "--remote", "nope"], "fr");
    expect(named.stderr).toBe(
      "Erreur NO_REMOTE : Aucun dépôt distant Git ne s'appelle nope : rien n'a été fait. `git remote -v` liste ceux qui sont configurés.\n",
    );
    const bare = run(["journal"]);
    expect(bare.stderr).toBe(
      "Error INVALID_ARGUMENTS: Invalid arguments: journal (sync, status)\n",
    );
    for (const args of [
      ["journal"],
      ["init", "--recreate-remote"],
      ["journal", "push"],
      ["journal", "sync", "x"],
      ["journal", "status", "x"],
      ["journal", "status", "--remote", "origin"],
      ["sync", "--remote", "origin"],
    ]) {
      const { status, stderr } = run(args);
      expect(status, args.join(" ")).toBe(1);
      expect(stderr, args.join(" ")).toContain("Error INVALID_ARGUMENTS:");
    }
  });

  it("journal status: two clones of one machine sync, and write the same state.json", async () => {
    git(cwd, ["remote", "add", "origin", remote]);
    await mkdir(join(cwd, ".agentplugged"), { recursive: true });
    await appendEvents(cwd, 1);
    expect(run(["journal", "sync"]).status).toBe(0);

    // A second clone on the same machine (same key): each one writes after the same event.
    const other = await mkdtemp(join(tmpdir(), "agentplugged-other-"));
    const mine = cwd;
    try {
      git(other, ["clone", "-q", remote, "."]);
      identify(other);
      await mkdir(join(other, ".agentplugged"), { recursive: true });
      cwd = other;
      expect(run(["journal", "sync"]).status).toBe(0);
      await appendEvents(other, 1);
      await appendEvents(mine, 1);
      expect(run(["journal", "sync"]).status).toBe(0);
      cwd = mine;
      expect(run(["journal", "sync"]).status).toBe(0);

      // The CLI never applies the types reserved to tests: it lists them as ignored.
      const here = run(["journal", "status"]);
      expect(here.stderr).toBe("");
      expect(here.status).toBe(0);
      // Without a system keychain, the status says that the sensitive content is not shown.
      const keychainWarning = KEYCHAIN
        ? ""
        : "\\nWarnings:\\n {2}The system keychain could not be read \\([^\\n]*\\): the sensitive content is not shown\\.\\n";
      expect(here.stdout).toMatch(
        new RegExp(
          `^State of the product\\n {2}Product: 01JZ0000000000000000000000\\n {2}Devices: 1\\n {2}Creators' keys: 0\\n {2}Events applied: 2\\n\\nEvents ignored \\(3\\):\\n(?: {2}\\w{26}: its type is reserved to tests\\n){3}${keychainWarning}\\nState written to \\.agentplugged\\/\\.cache\\/state\\.json\\.\\n$`,
        ),
      );
      expect(run(["journal", "status"]).stdout).toContain(
        "\n.agentplugged/.cache/state.json is already up to date.\n",
      );
      cwd = other;
      expect(run(["journal", "sync"]).status).toBe(0);
      const there = run(["journal", "status"], "fr");
      expect(there.stderr).toBe("");
      expect(there.stdout).toContain("État du produit\n  Produit : 01JZ0000000000000000000000\n");
      expect(there.stdout).toContain("  Événements appliqués : 2\n\nÉvénements ignorés (3) :\n");
      expect(there.stdout).toContain("État écrit dans .agentplugged/.cache/state.json.\n");
      const statePath = ".agentplugged/.cache/state.json";
      expect(await readFile(join(other, statePath), "utf8")).toBe(
        await readFile(join(mine, statePath), "utf8"),
      );
    } finally {
      cwd = mine;
      await rm(other, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
    }
  }, 120_000);
});
